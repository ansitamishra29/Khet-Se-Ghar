// ========================================
// FARMER DASHBOARD NUMBER LOCALIZATION
// ========================================

(function () {

    const hindiDigits = "०१२३४५६७८९";
    const odiaDigits = "୦୧୨୩୪୫୬୭୮୯";

    function localizeFarmerNumbers() {

        const language = localStorage.getItem("ksg_language") || "en";

        let digitSet = null;

        if (language === "hi") {
            digitSet = hindiDigits;
        } else if (language === "or") {
            digitSet = odiaDigits;
        }

        document.querySelectorAll("[data-localize-numbers]").forEach(element => {

            const walker = document.createTreeWalker(
                element,
                NodeFilter.SHOW_TEXT
            );

            let textNode;

            while (textNode = walker.nextNode()) {

                // Convert previously localized digits back to English first.
                let originalText = textNode.textContent
                    .replace(/[०-९]/g, digit => String(hindiDigits.indexOf(digit)))
                    .replace(/[୦-୯]/g, digit => String(odiaDigits.indexOf(digit)));

                // Apply the selected language's digits.
                if (digitSet) {
                    originalText = originalText.replace(/[0-9]/g, digit => {
                        return digitSet[Number(digit)];
                    });
                }

                textNode.textContent = originalText;
            }

        });

    }

    // Run whenever the dashboard language changes.
    document.addEventListener(
        "ksgLanguageChanged",
        localizeFarmerNumbers
    );

})();
